#!/usr/bin/env python3
"""
Export Contracts Script
Dumps OpenAPI schema, JSON Schemas, TypeScript types and Dart models from canonical Pydantic contracts.
"""
import json
import os
import subprocess
import sys
from pathlib import Path

# Add services/api to sys.path
ROOT_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT_DIR / "services" / "api"))
sys.path.insert(0, str(ROOT_DIR / "contracts" / "src"))

from app.main import app
import td_contracts

def export_openapi() -> Path:
    out_dir = ROOT_DIR / "contracts" / "generated"
    out_dir.mkdir(parents=True, exist_ok=True)
    openapi_file = out_dir / "openapi.json"
    
    schema = app.openapi()
    with open(openapi_file, "w", encoding="utf-8") as f:
        json.dump(schema, f, indent=2)
    print(f"[OK] Exported OpenAPI specification to {openapi_file}")
    return openapi_file

def export_json_schemas() -> None:
    schema_dir = ROOT_DIR / "contracts" / "generated" / "jsonschema"
    schema_dir.mkdir(parents=True, exist_ok=True)

    model_names = [
        "EventIngest",
        "EventExtendRequest",
        "EventOut",
        "VlmVerificationIngest",
        "VlmVerificationResponse",
        "HumanVerificationRequest",
        "ChangesResponse",
        "ChatRequest",
        "ChatResponse",
        "ErrorEnvelope",
        "WsEnvelope",
        "InternalConfigOut",
        "WorkerHeartbeatRequest"
    ]

    for name in model_names:
        cls = getattr(td_contracts, name, None)
        if cls and hasattr(cls, "model_json_schema"):
            schema_file = schema_dir / f"{name}.json"
            with open(schema_file, "w", encoding="utf-8") as f:
                json.dump(cls.model_json_schema(), f, indent=2)
            print(f"[OK] Exported JSON schema: {schema_file.name}")

def export_typescript(openapi_file: Path) -> None:
    ts_out = ROOT_DIR / "apps" / "dashboard" / "src" / "api" / "generated" / "schema.ts"
    ts_out.parent.mkdir(parents=True, exist_ok=True)
    
    cmd = ["npx", "-y", "openapi-typescript", str(openapi_file), "-o", str(ts_out)]
    print(f"Running: {' '.join(cmd)}")
    result = subprocess.run(cmd, capture_output=True, text=True, shell=True)
    if result.returncode != 0:
        print(f"[ERROR] Failed to generate TypeScript types: {result.stderr}")
    else:
        print(f"[OK] Generated TypeScript types in {ts_out}")

def export_dart() -> None:
    dart_out = ROOT_DIR / "apps" / "mobile" / "lib" / "data" / "generated" / "models.dart"
    dart_out.parent.mkdir(parents=True, exist_ok=True)
    
    dart_code = '''// GENERATED CODE FROM CANONICAL CONTRACTS - DO NOT EDIT MANUALLY
// Generated by scripts/export-contracts.py
// ignore_for_file: constant_identifier_names

import 'dart:convert';

enum EventStatus {
  DETECTED,
  VERIFYING,
  CONFIRMED,
  FALSE_POSITIVE,
  NEEDS_REVIEW,
}

enum Severity {
  LOW,
  MEDIUM,
  HIGH,
  CRITICAL,
}

enum VerifiedBy {
  NONE,
  AI,
  HUMAN,
}

enum HumanAction {
  CONFIRM,
  MARK_FALSE_POSITIVE,
  REOPEN,
}

enum MediaKind {
  KEYFRAME,
  CROP,
  CLIP,
}

class CameraRef {
  final String id;
  final String name;

  CameraRef({required this.id, required this.name});

  factory CameraRef.fromJson(Map<String, dynamic> json) => CameraRef(
        id: json['id'] as String,
        name: json['name'] as String,
      );

  Map<String, dynamic> toJson() => {'id': id, 'name': name};
}

class CategoryRef {
  final String key;
  final String label;

  CategoryRef({required this.key, required this.label});

  factory CategoryRef.fromJson(Map<String, dynamic> json) => CategoryRef(
        key: json['key'] as String,
        label: json['label'] as String,
      );

  Map<String, dynamic> toJson() => {'key': key, 'label': label};
}

class MediaItemOut {
  final String id;
  final MediaKind kind;
  final String role;
  final String url;
  final int width;
  final int height;
  final int? offsetMs;

  MediaItemOut({
    required this.id,
    required this.kind,
    required this.role,
    required this.url,
    required this.width,
    required this.height,
    this.offsetMs,
  });

  factory MediaItemOut.fromJson(Map<String, dynamic> json) => MediaItemOut(
        id: json['id'] as String,
        kind: MediaKind.values.byName(json['kind'] as String),
        role: json['role'] as String,
        url: json['url'] as String,
        width: json['width'] as int,
        height: json['height'] as int,
        offsetMs: json['offset_ms'] as int?,
      );

  Map<String, dynamic> toJson() => {
        'id': id,
        'kind': kind.name,
        'role': role,
        'url': url,
        'width': width,
        'height': height,
        'offset_ms': offsetMs,
      };
}

class TrackRef {
  final int trackId;
  final String className;
  final int? firstFrame;
  final int? lastFrame;

  TrackRef({
    required this.trackId,
    required this.className,
    this.firstFrame,
    this.lastFrame,
  });

  factory TrackRef.fromJson(Map<String, dynamic> json) => TrackRef(
        trackId: json['track_id'] as int,
        className: json['class'] as String,
        firstFrame: json['first_frame'] as int?,
        lastFrame: json['last_frame'] as int?,
      );

  Map<String, dynamic> toJson() => {
        'track_id': trackId,
        'class': className,
        if (firstFrame != null) 'first_frame': firstFrame,
        if (lastFrame != null) 'last_frame': lastFrame,
      };
}

class EventOut {
  final String id;
  final CameraRef camera;
  final CategoryRef category;
  final EventStatus status;
  final String? statusReason;
  final VerifiedBy verifiedBy;
  final bool aiDisagrees;
  final Severity severity;
  final double yoloConfidence;
  final double peakConfidence;
  final String? summary;
  final String firstSeenAt;
  final String lastSeenAt;
  final int? mediaOffsetMs;
  final List<TrackRef> trackRefs;
  final List<MediaItemOut> media;
  final int changeSeq;
  final String createdAt;
  final String updatedAt;

  EventOut({
    required this.id,
    required this.camera,
    required this.category,
    required this.status,
    this.statusReason,
    required this.verifiedBy,
    required this.aiDisagrees,
    required this.severity,
    required this.yoloConfidence,
    required this.peakConfidence,
    this.summary,
    required this.firstSeenAt,
    required this.lastSeenAt,
    this.mediaOffsetMs,
    required this.trackRefs,
    required this.media,
    required this.changeSeq,
    required this.createdAt,
    required this.updatedAt,
  });

  factory EventOut.fromJson(Map<String, dynamic> json) => EventOut(
        id: json['id'] as String,
        camera: CameraRef.fromJson(json['camera'] as Map<String, dynamic>),
        category: CategoryRef.fromJson(json['category'] as Map<String, dynamic>),
        status: EventStatus.values.byName(json['status'] as String),
        statusReason: json['status_reason'] as String?,
        verifiedBy: VerifiedBy.values.byName(json['verified_by'] as String),
        aiDisagrees: json['ai_disagrees'] as bool? ?? false,
        severity: Severity.values.byName(json['severity'] as String),
        yoloConfidence: (json['yolo_confidence'] as num).toDouble(),
        peakConfidence: (json['peak_confidence'] as num).toDouble(),
        summary: json['summary'] as String?,
        firstSeenAt: json['first_seen_at'] as String,
        lastSeenAt: json['last_seen_at'] as String,
        mediaOffsetMs: json['media_offset_ms'] as int?,
        trackRefs: (json['track_refs'] as List<dynamic>?)
                ?.map((e) => TrackRef.fromJson(e as Map<String, dynamic>))
                .toList() ??
            [],
        media: (json['media'] as List<dynamic>?)
                ?.map((e) => MediaItemOut.fromJson(e as Map<String, dynamic>))
                .toList() ??
            [],
        changeSeq: json['change_seq'] as int,
        createdAt: json['created_at'] as String,
        updatedAt: json['updated_at'] as String,
      );

  Map<String, dynamic> toJson() => {
        'id': id,
        'camera': camera.toJson(),
        'category': category.toJson(),
        'status': status.name,
        'status_reason': statusReason,
        'verified_by': verifiedBy.name,
        'ai_disagrees': aiDisagrees,
        'severity': severity.name,
        'yolo_confidence': yoloConfidence,
        'peak_confidence': peakConfidence,
        'summary': summary,
        'first_seen_at': firstSeenAt,
        'last_seen_at': lastSeenAt,
        'media_offset_ms': mediaOffsetMs,
        'track_refs': trackRefs.map((e) => e.toJson()).toList(),
        'media': media.map((e) => e.toJson()).toList(),
        'change_seq': changeSeq,
        'created_at': createdAt,
        'updated_at': updatedAt,
      };
}

class HumanVerificationRequest {
  final String clientActionId;
  final HumanAction action;
  final String? note;
  final String? correctedCategory;

  HumanVerificationRequest({
    required this.clientActionId,
    required this.action,
    this.note,
    this.correctedCategory,
  });

  Map<String, dynamic> toJson() => {
        'client_action_id': clientActionId,
        'action': action.name,
        if (note != null) 'note': note,
        if (correctedCategory != null) 'corrected_category': correctedCategory,
      };
}

class ChangesResponse {
  final List<EventOut> items;
  final int nextAfter;
  final bool hasMore;
  final int headSeq;

  ChangesResponse({
    required this.items,
    required this.nextAfter,
    required this.hasMore,
    required this.headSeq,
  });

  factory ChangesResponse.fromJson(Map<String, dynamic> json) => ChangesResponse(
        items: (json['items'] as List<dynamic>)
            .map((e) => EventOut.fromJson(e as Map<String, dynamic>))
            .toList(),
        nextAfter: json['next_after'] as int,
        hasMore: json['has_more'] as bool,
        headSeq: json['head_seq'] as int,
      );

  Map<String, dynamic> toJson() => {
        'items': items.map((e) => e.toJson()).toList(),
        'next_after': nextAfter,
        'has_more': hasMore,
        'head_seq': headSeq,
      };
}
'''
    with open(dart_out, "w", encoding="utf-8") as f:
        f.write(dart_code)
    print(f"[OK] Generated Dart models in {dart_out}")

if __name__ == "__main__":
    openapi_path = export_openapi()
    export_json_schemas()
    export_typescript(openapi_path)
    export_dart()
    print("[SUCCESS] All contracts and types exported successfully.")
